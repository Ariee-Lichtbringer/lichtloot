import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const {PGlite}=await import(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const db=new PGlite();
const src=fs.readFileSync(new URL('../src/server.js',import.meta.url),'utf8');
const extract=name=>{const start=src.indexOf('async function '+name+'(');return src.slice(start,src.indexOf('\n}\n',start)+2);};
await db.exec(`create table raids(id text,guild_id text,external_raid_id text,raid_type text,raid_date date,raid_time text,deleted_at timestamptz,status text,created_at timestamptz,raidhelper_enabled boolean,raid_pin text);
  insert into raids values('original','guild','OLD','mc','2026-09-25','21:00',null,'geschlossen',now(),false,'KEEP');
  create table p0_only_events as select id,guild_id,external_raid_id as external_p0_id,raid_type,raid_date,raid_time,deleted_at,status,created_at from raids;`);
const ctx=vm.createContext({Date,query:db.query.bind(db),inTransaction:fn=>fn(),clean:v=>String(v??'').trim(),normalizeRaidType:v=>v,parseDateValue:v=>v,displayRaidName:v=>v,normalizeStatus:v=>v,requireConfiguredSpecialRaidType:async()=>{},raidTypeSearchValues:v=>[v],normalizeRaidRow:v=>v,normalizeP0OnlyEventRow:v=>v});
for(const name of ['createRaidRecord','createRaidRecordLocked','createP0OnlyEventLocked'])vm.runInContext(extract(name),ctx);
const request={guildId:'guild',query:{raid:'mc',raidId:'NEW',raidDate:'2026-09-25',raidTime:'21:00:00',raidHelperEnabled:true}};
let result=await ctx.createRaidRecord(request);
assert.equal(result.id,'original');assert.equal(result.reused,true);assert.equal(result.raid_pin,'KEEP');
await assert.rejects(ctx.createRaidRecord({...request,query:{...request.query,updateExisting:'true'}}),e=>e.statusCode===409);
await db.query("update raids set status='archiviert'");
assert.equal((await ctx.createRaidRecord(request)).id,'original');
result=await ctx.createP0OnlyEventLocked({guildId:'guild',params:request.query},db.query.bind(db));
assert.equal(result.id,'original');
assert.equal((await db.query('select count(*) from raids')).rows[0].count,1);
await db.close();
console.log('PASS: recreated signup reuses original ID/PIN across modes and time formats; updateExisting cannot bypass conflict; P0-only store reuses occurrence.');
